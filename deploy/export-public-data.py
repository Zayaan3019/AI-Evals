"""Export one tenant from the local stack into a bundle for restore-public-data.sh.

    python deploy/export-public-data.py --tenant public --out bundle.tgz

Exports the tenant's rows from every tenant-scoped Postgres table (API keys
excluded: the public instance is read-only and needs none), its ClickHouse
spans in Native format, the Alembic revision, and the compose and config
files the host should run. Uses the local docker containers' clients, so it
needs nothing beyond docker on the machine running it.
"""

from __future__ import annotations

import argparse
import datetime as dt
import io
import subprocess
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PG = ["docker", "exec", "agentlens-postgres-1", "psql", "-U", "agentlens", "-d", "agentlens", "-v", "ON_ERROR_STOP=1"]
CH = ["docker", "exec", "agentlens-clickhouse-1", "clickhouse-client"]

# Foreign-key order: parents before children.
TABLES = ["datasets", "evaluators", "eval_cases", "eval_runs", "eval_results", "human_labels"]
TRUNCATE = ["tenants", "api_keys", *TABLES]
FILES = [
    "docker-compose.yml",
    "docker-compose.prod.yml",
    "docker-compose.public.yml",
    "deploy/clickhouse-low-memory.xml",
    "deploy/clickhouse-low-memory-users.xml",
]


def run(cmd: list[str]) -> bytes:
    return subprocess.run(cmd, check=True, capture_output=True).stdout


def psql(sql: str) -> str:
    return run([*PG, "-Atc", sql]).decode().strip()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tenant", required=True, help="tenant slug")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    tenant_id = psql(f"select id from tenants where slug = '{args.tenant}'")
    if not tenant_id:
        raise SystemExit(f"no tenant {args.tenant!r}")

    members: dict[str, bytes] = {}

    def copy_out(table: str, where: str) -> list[str]:
        data = run([*PG, "-c", f"\\copy (select * from {table} where {where}) to stdout with csv header"])
        members[f"pg/{table}.csv"] = data
        return data.split(b"\n", 1)[0].decode().strip().split(",")

    restore = ["-- generated by deploy/export-public-data.py; run with psql -1", f"TRUNCATE {', '.join(TRUNCATE)} CASCADE;"]
    columns = copy_out("tenants", f"id = '{tenant_id}'")
    restore.append(f"\\copy tenants ({', '.join(columns)}) from '/tmp/restore/tenants.csv' with csv header")
    counts = {}
    for table in TABLES:
        columns = copy_out(table, f"tenant_id = '{tenant_id}'")
        restore.append(f"\\copy {table} ({', '.join(columns)}) from '/tmp/restore/{table}.csv' with csv header")
        counts[table] = int(psql(f"select count(*) from {table} where tenant_id = '{tenant_id}'"))
    members["pg/restore.sql"] = ("\n".join(restore) + "\n").encode()
    members["pg/alembic_version.txt"] = psql("select version_num from alembic_version").encode()

    members["spans.native"] = run([*CH, "-q", f"select * from agentlens.spans where tenant_id = '{args.tenant}' format Native"])
    span_count = run([*CH, "-q", f"select count() from agentlens.spans where tenant_id = '{args.tenant}'"]).decode().strip()

    for rel in FILES:
        members[f"files/{rel}"] = (ROOT / rel).read_bytes()

    manifest = (
        f"tenant={args.tenant} exported={dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')} "
        f"spans={span_count} " + " ".join(f"{k}={v}" for k, v in counts.items())
    )
    members["manifest.txt"] = manifest.encode()

    with tarfile.open(args.out, "w:gz") as tar:
        for name, data in members.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    print(manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
